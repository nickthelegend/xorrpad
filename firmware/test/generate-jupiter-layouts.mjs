/** Generate bounded route-plan layouts from Jupiter's public on-chain Anchor IDL. */
import {createRequire} from 'node:module';
import {inflateSync} from 'node:zlib';
import {createHash} from 'node:crypto';
import {writeFile} from 'node:fs/promises';
const require=createRequire(new URL('../../desk/package.json',import.meta.url));
const {PublicKey,Connection}=require('@solana/web3.js');
const program=new PublicKey('JUP6LkbZbjS1jKKwapdHNy74zcZ3tLUZoi5QNyVTaV4');
const [base]=PublicKey.findProgramAddressSync([],program);
const address=await PublicKey.createWithSeed(base,'anchor:idl',program);
const c=new Connection('https://api.mainnet-beta.solana.com',{fetch:(url,options)=>fetch(url,{...options,signal:AbortSignal.timeout(20000)})});
const {context,value}=await c.getAccountInfoAndContext(address);
if(!value || !value.owner.equals(program))throw Error('public Jupiter IDL unavailable');
const json=inflateSync(value.data.subarray(44,44+value.data.readUInt32LE(40))),idl=JSON.parse(json);
const variants=idl.types.find(t=>t.name.toLowerCase()==='swap').type.variants;
const primitives={bool:1,u8:1,i8:1,u16:2,i16:2,u32:4,i32:4,u64:8,i64:8,u128:16,i128:16};
function layout(type,stack=[]){
 if(typeof type==='string')return type in primitives?{size:primitives[type],checks:type==='bool'?[0]:[]}:null;
 if(type?.defined){
  const name=typeof type.defined==='string'?type.defined:type.defined.name;
  if(stack.includes(name))return null;
  const t=idl.types.find(t=>t.name===name)?.type;
  if(t?.kind==='enum' && t.variants.length===2 && t.variants.every(v=>!v.fields?.length))return {size:1,checks:[0]};
  if(t?.kind==='struct')return fields(t.fields,[...stack,name]);
 }
 return null;
}
function fields(values=[],stack=[]){
 let size=0,checks=[];
 for(const field of values){const part=layout(field.type||field,stack);if(!part || size+part.size>63)return null;checks.push(...part.checks.map(n=>n+size));size+=part.size;}
 return {size,checks};
}
const hash=createHash('sha256').update(json).digest('hex');
const rows=variants.map((v,i)=>{const l=fields(v.fields);const mask=l?l.checks.reduce((m,n)=>m|(1n<<BigInt(n)),0n):0n;return `  {${l?l.size:-1},${mask}ULL}, // ${i}: ${v.name}`;});
const header=`#pragma once\n// Generated by firmware/test/generate-jupiter-layouts.mjs; do not edit.\n// Public Anchor IDL ${address.toBase58()}, slot ${context.slot}.\n// Inflated IDL SHA256 ${hash}\n// Dynamic/unsupported payloads (-1) require blind signing.\n#include <cstdint>\nnamespace xorr::solana {\nstruct JupiterLayout {int16_t size;uint64_t boolMask;};\ninline constexpr JupiterLayout jupiterLayouts[]={\n${rows.join('\n')}\n};\n}\n`;
await writeFile(new URL('../xorrpad/logic/jupiter-layouts.h',import.meta.url),header);
console.log(`Generated ${variants.length} layouts from public IDL ${address.toBase58()} at slot ${context.slot}`);
